const LanguageContext = createContext<LanguageContextValue | null>(null);

function getInitialLanguage(): Language {
  try {
    return window.localStorage.getItem("tasami-language") === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);
  const value = useMemo<LanguageContextValue>(
    () => ({
      language,
      direction: language === "ar" ? "rtl" : "ltr",
      isEnglish: language === "en",
      toggleLanguage: () => {
        setLanguage((current) => (current === "ar" ? "en" : "ar"));
      },
      t: (arabicText) => {
        const status = statusTranslations[arabicText];
        if (status) return status[language];
        return language === "en" ? translations[arabicText] ?? arabicText : arabicText;
      },
    }),
    [language],
  );

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    try {
      window.localStorage.setItem("tasami-language", language);
    } catch (error) {
      console.error("Could not save the selected language:", error);
    }
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
}
